package de.westnordost.streetcomplete.quests.contract

import kotlin.test.assertEquals

internal fun assertContractCoverage(registeredNames: Set<String>) {
    val fixtures = questContractFixtures()
    val covered = fixtures.map { it.quest.name }.toSet()
    assertEquals(registeredNames, covered + questsWithoutContract,
        "New quests need a contract; remove covered or retired quests from the allow-list")
    assertEquals(emptySet(), covered.intersect(questsWithoutContract),
        "A covered quest must leave the allow-list")
    fixtures.forEach { it.verify() }
}

